#Import Colab userdata
from google.colab import userdata

#step2: Retrieve Gemini API key
api_key = userdata.get("GEMINI_API_KEY")

#verify api key
if not api_key:
  raise ValueError("Missing Gemini API key")
print("Gemini API key loaded successfully.")

#Sever to client
#Import Gemini SDK
from google import genai
#step 3: Initialize Gemini client to establish the cnnection with gemini AI server
client = genai.Client(api_key=api_key)

print("Gemini client intialized succesffully.")

#Step4: Send the prompt to Gemini model
response = client.models.generate_content(
    model="gemini-3.5-flash",
    contents="What is Artificial Intelligence?Explain in Simple words."
)

#step5: Display generated response
print("\nLLM Response:")
print(response.text)